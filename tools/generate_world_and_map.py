#!/usr/bin/env python3
"""Generate the Gazebo world AND the matching Nav2 occupancy map from one layout.

Why: a hand-drawn or SLAM-built map can drift from the simulated world (moved
obstacles, scaling errors). Writing both files from the same list of shapes
guarantees AMCL localizes against a map that matches Gazebo exactly.

Only the Python standard library is used, so this runs anywhere:
    python3 tools/generate_world_and_map.py
"""
from pathlib import Path

PKG = Path(__file__).resolve().parents[1] / "tb3_nav2_demo"
WORLD_NAME = "obstacle_course"

# ---------------------------------------------------------------- layout ----
# Room: wall centerlines at x = +-4 m and y = +-3 m (8 m x 6 m).
# Two divider walls force an S-shaped route; crates and pillars add clutter.
WALL_H = 0.5   # wall / obstacle height (m), tall enough for the LDS lidar
WALL_T = 0.15  # wall thickness (m)

GREY = (0.55, 0.55, 0.58)
ORANGE = (0.95, 0.55, 0.15)
BLUE = (0.25, 0.45, 0.85)

# (name, center_x, center_y, size_x, size_y, colour)
BOXES = [
    ("wall_north", 0.0, 3.0, 8.0 + WALL_T, WALL_T, GREY),
    ("wall_south", 0.0, -3.0, 8.0 + WALL_T, WALL_T, GREY),
    ("wall_east", 4.0, 0.0, WALL_T, 6.0 + WALL_T, GREY),
    ("wall_west", -4.0, 0.0, WALL_T, 6.0 + WALL_T, GREY),
    # Divider A: x = -1.5, from the south wall up to y = 0.8 (gap at the top)
    ("divider_a", -1.5, -1.1, WALL_T, 3.8, GREY),
    # Divider B: x = +1.5, from the north wall down to y = -0.8 (gap at the bottom)
    ("divider_b", 1.5, 1.1, WALL_T, 3.8, GREY),
    ("crate_1", -2.8, 1.5, 0.5, 0.5, ORANGE),
    ("crate_2", 0.0, 2.0, 0.5, 0.5, ORANGE),
    ("crate_3", 2.8, -1.5, 0.6, 0.4, ORANGE),
]

# (name, center_x, center_y, radius, colour)
CYLINDERS = [
    ("pillar_1", 0.0, 0.0, 0.25, BLUE),
    ("pillar_2", 0.0, -1.8, 0.20, BLUE),
]

# ------------------------------------------------------------------- map ----
RESOLUTION = 0.05            # m / pixel (Nav2 default)
ORIGIN = (-4.5, -3.5)        # world coords of the map's lower-left corner
SIZE = (9.0, 7.0)            # map extent in metres
FREE, OCCUPIED, UNKNOWN = 254, 0, 205


def _material(rgb):
    r, g, b = rgb
    return (f"<material><ambient>{r} {g} {b} 1</ambient>"
            f"<diffuse>{r} {g} {b} 1</diffuse>"
            f"<specular>0.1 0.1 0.1 1</specular></material>")


def _box_model(name, cx, cy, sx, sy, rgb):
    geom = f"<box><size>{sx:.3f} {sy:.3f} {WALL_H}</size></box>"
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{cx} {cy} {WALL_H / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry>{geom}</geometry></collision>
        <visual name="visual"><geometry>{geom}</geometry>{_material(rgb)}</visual>
      </link>
    </model>"""


def _cylinder_model(name, cx, cy, radius, rgb):
    geom = f"<cylinder><radius>{radius}</radius><length>{WALL_H}</length></cylinder>"
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{cx} {cy} {WALL_H / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry>{geom}</geometry></collision>
        <visual name="visual"><geometry>{geom}</geometry>{_material(rgb)}</visual>
      </link>
    </model>"""


def build_world():
    models = "".join(_box_model(*b) for b in BOXES)
    models += "".join(_cylinder_model(*c) for c in CYLINDERS)
    # Ground plane and light are defined inline (no model:// lookups), so the
    # world loads offline and never waits on the Gazebo model database.
    return f"""<?xml version="1.0"?>
<!-- AUTO-GENERATED by tools/generate_world_and_map.py - edit the layout there. -->
<sdf version="1.6">
  <world name="{WORLD_NAME}">
    <gravity>0 0 -9.8</gravity>
    <physics type="ode">
      <real_time_update_rate>1000.0</real_time_update_rate>
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1</real_time_factor>
    </physics>
    <scene>
      <ambient>0.5 0.5 0.5 1</ambient>
      <background>0.75 0.8 0.85 1</background>
      <shadows>false</shadows>
    </scene>
    <gui fullscreen="0">
      <camera name="user_camera">
        <pose>0 -8.5 9.5 0 0.85 1.5708</pose>
        <view_controller>orbit</view_controller>
      </camera>
    </gui>
    <light name="sun" type="directional">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.2 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          <surface><friction><ode><mu>100</mu><mu2>50</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <cast_shadows>false</cast_shadows>
          <geometry><plane><normal>0 0 1</normal><size>40 40</size></plane></geometry>
          {_material((0.85, 0.85, 0.82))}
        </visual>
      </link>
    </model>{models}
  </world>
</sdf>
"""


def _occupied(x, y):
    for _, cx, cy, sx, sy, _ in BOXES:
        if abs(x - cx) <= sx / 2 and abs(y - cy) <= sy / 2:
            return True
    for _, cx, cy, r, _ in CYLINDERS:
        if (x - cx) ** 2 + (y - cy) ** 2 <= r ** 2:
            return True
    return False


def _outside_room(x, y):
    return abs(x) > 4.0 + WALL_T / 2 or abs(y) > 3.0 + WALL_T / 2


def build_map():
    width = round(SIZE[0] / RESOLUTION)
    height = round(SIZE[1] / RESOLUTION)
    pixels = bytearray()
    for row in range(height):                     # row 0 is the TOP of the image
        y = ORIGIN[1] + (height - 1 - row + 0.5) * RESOLUTION
        for col in range(width):
            x = ORIGIN[0] + (col + 0.5) * RESOLUTION
            if _occupied(x, y):
                pixels.append(OCCUPIED)
            elif _outside_room(x, y):
                pixels.append(UNKNOWN)
            else:
                pixels.append(FREE)
    header = f"P5\n# {WORLD_NAME}\n{width} {height}\n255\n".encode()
    return header + bytes(pixels), width, height


def build_map_yaml():
    # free_thresh 0.196 keeps grey (205) pixels as "unknown" rather than "free".
    return (f"image: {WORLD_NAME}.pgm\n"
            f"mode: trinary\n"
            f"resolution: {RESOLUTION}\n"
            f"origin: [{ORIGIN[0]}, {ORIGIN[1]}, 0.0]\n"
            f"negate: 0\n"
            f"occupied_thresh: 0.65\n"
            f"free_thresh: 0.196\n")


def main():
    (PKG / "worlds").mkdir(parents=True, exist_ok=True)
    (PKG / "maps").mkdir(parents=True, exist_ok=True)
    (PKG / "worlds" / f"{WORLD_NAME}.world").write_text(build_world())
    pgm, w, h = build_map()
    (PKG / "maps" / f"{WORLD_NAME}.pgm").write_bytes(pgm)
    (PKG / "maps" / f"{WORLD_NAME}.yaml").write_text(build_map_yaml())
    print(f"Wrote world + {w}x{h} px map ({RESOLUTION} m/px) to {PKG}")


if __name__ == "__main__":
    main()
